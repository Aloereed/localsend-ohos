const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { load, mocks, handles, capabilities } = require('./host-runtime.cjs');
const { AppStore } = load('model/AppStore');
(async () => {
  const work = path.join(__dirname, '../logs/selection-cancel-' + Date.now()).replaceAll('\\', '/');
  await fs.mkdir(work + '/folder', { recursive: true });
  await fs.writeFile(work + '/folder/a.txt', 'a'); await fs.writeFile(work + '/folder/b.txt', 'b');
  const store = new AppStore(); await store.init({ filesDir: work, getApplicationContext: () => ({ setColorMode() {} }) });
  store.addText('draft'); const original = store.files;
  const picker = mocks['@kit.CoreFileKit'].picker, disk = mocks['@kit.CoreFileKit'].fileIo;
  picker.DocumentSelectOptions = class {}; picker.DocumentSelectMode = { FILE: 0, FOLDER: 1 };
  let uris = [work + '/folder']; picker.DocumentViewPicker = class { async select() { return uris; } };
  capabilities.folderSelection = true;
  const open = disk.open; let release, reached;
  const reading = new Promise(resolve => { reached = resolve; });
  const blocked = new Promise(resolve => { release = resolve; });
  disk.open = async (...args) => { const file = await open(...args); if (args[0].endsWith('/b.txt')) { reached(); await blocked; } return file; };
  const pending = store.selectFiles('folder'); await reading;
  assert.equal(store.selecting, true); assert.equal(store.selectionReadCount, 1);
  store.cancelSelection(); assert.equal(store.selectionCancelled, true); assert.equal(store.busy, true, 'do not start another scan while an old I/O operation owns a descriptor');
  release(); assert.equal(await pending, false); assert.equal(store.files, original);
  assert.equal(store.selecting, false); assert.equal(store.busy, false); assert.equal(handles.size, 0); assert.equal(store.error, '');
  disk.open = open;
  assert.equal(await store.selectFiles('folder'), true); assert.equal(store.selectionReadCount, 2); assert.equal(store.selectionCancelled, false);
  uris = [work + '/folder/a.txt'];
  picker.DocumentViewPicker = class { async select() { store.cancelSelection(); return uris; } };
  assert.equal((await store.selectAttachments('file')).length, 0); assert.equal(handles.size, 0);
  capabilities.folderSelection = false; store.downloadDirectory = work; store.downloadAccess = true;
  store.onPickDownloadDirectory = async () => work + '/folder';
  const listFile = disk.listFile;
  disk.listFile = async (...args) => { const result = await listFile(...args); store.cancelSelection(); return result; };
  const before = store.files;
  assert.equal(await store.selectFiles('folder'), false); assert.equal(store.files, before); assert.equal(handles.size, 0);
  disk.listFile = listFile;
  console.log('PASS cancel during open file I/O, original selection preservation, descriptor cleanup, next scan recovery, attachments and custom-folder traversal');
})().catch(error => { console.error(error); process.exitCode = 1; });
