const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { load, mocks, handles, capabilities } = require('./host-runtime.cjs');
const { AppStore, HistoryEntry } = load('model/AppStore');
(async () => {
  const root = path.join(__dirname, '../logs/download-fixture-' + Date.now()); await fs.mkdir(root, { recursive: true });
  const store = new AppStore(); store.downloadDirectory = path.join(root, 'Download/com.aloereed.aloesend').replaceAll('\\', '/');
  await store.init({ filesDir: root, getApplicationContext: () => ({ setColorMode() {} }) });
  let requested = 0, accepted = true, persistCalls = 0;
  mocks['@kit.CoreFileKit'].picker.DocumentSaveOptions = class {};
  mocks['@kit.CoreFileKit'].picker.DocumentPickerMode = { DOWNLOAD: 7 };
  mocks['@kit.CoreFileKit'].picker.DocumentViewPicker = class { async save(options) { assert.equal(options.pickerMode, 7); requested++; return accepted ? ['file://download-grant'] : []; } };
  mocks['@kit.CoreFileKit'].fileShare.activatePermission = async () => persistCalls++;
  await store.ensureDownloadAccess(); assert.equal(requested, 1); assert.equal(store.settings.destinationMode, 'download');
  assert.equal(store.settings.destination, store.downloadDirectory); assert.deepEqual(await fs.readdir(store.downloadDirectory), []);
  const entry = new HistoryEntry(); entry.name = 'folder/file.bin'; entry.path = path.join(root, 'source');
  await fs.writeFile(entry.path, Buffer.from([0, 128, 255]));
  await store.saveReceivedCopy(entry); assert.equal(entry.exportedPath, store.downloadDirectory + '/folder/file.bin');
  await fs.writeFile(entry.path, Buffer.from([1, 2, 3])); await store.saveReceivedCopy(entry);
  assert.equal(entry.exportedPath, store.downloadDirectory + '/folder/file (1).bin');
  assert.deepEqual(await fs.readFile(store.downloadDirectory + '/folder/file.bin'), Buffer.from([0, 128, 255]));
  assert.equal(persistCalls, 0, 'DOWNLOAD grant must not be treated as a persisted folder-picker policy');
  const oldCopy = entry.exportedPath;
  await store.saveReceivedCopy(entry, path.join(root, 'expired-folder'));
  assert.equal(entry.exportedPath, oldCopy); assert.equal(store.error, '');
  assert.match(store.notice, /旧保存目录暂不可用/); assert.equal(persistCalls, 1);
  assert.deepEqual(await fs.readFile(entry.path), Buffer.from([1, 2, 3]));
  store.settings.destinationMode = 'folder'; store.settings.destination = '/custom'; await store.ensureDownloadAccess();
  assert.equal(store.settings.destination, '/custom');
  accepted = false; await store.ensureDownloadAccess(); assert.equal(store.settings.destination, '/custom');
  accepted = true; await store.ensureDownloadAccess();
  let browsed = '';
  capabilities.folderSelection = false;
  store.onPickDownloadDirectory = async initial => { browsed = initial; return store.downloadDirectory + '/folder'; };
  assert.equal(await store.pickDestination(), store.downloadDirectory + '/folder'); assert.equal(browsed, store.downloadDirectory);
  capabilities.folderSelection = true;
  const custom = path.join(root, 'custom').replaceAll('\\', '/'); await fs.mkdir(custom);
  const calls = [];
  let selection = [custom], denied = false, pickerError;
  const kit = mocks['@kit.CoreFileKit'];
  kit.picker.DocumentSelectOptions = class {};
  kit.picker.DocumentSelectMode = { FOLDER: 1 };
  kit.picker.DocumentViewPicker = class { async select(options) {
    if (pickerError) throw pickerError;
    assert.equal(options.selectMode, 1); assert.equal(options.maxSelectNumber, 1); return selection;
  } };
  pickerError = Object.assign(new Error('unsupported'), { code: 801 });
  assert.equal(await store.pickDestination(), store.downloadDirectory + '/folder');
  pickerError = Object.assign(new Error('denied'), { code: 201 });
  await assert.rejects(store.pickDestination(), /denied/);
  pickerError = undefined;
  kit.fileShare.persistPermission = async policies => {
    calls.push(['persist', policies[0].uri, policies[0].operationMode]);
    if (denied) throw new Error('grant denied');
  };
  kit.fileShare.activatePermission = async policies => calls.push(['activate', policies[0].uri, policies[0].operationMode]);
  await store.chooseDestination(); assert.equal(store.settings.destination, custom);
  assert.deepEqual(calls, [['persist', custom, 3], ['activate', custom, 3]]);
  selection = []; await store.chooseDestination(); assert.equal(store.settings.destination, custom); assert.equal(calls.length, 2);
  denied = true; selection = [custom + '/denied']; await store.chooseDestination();
  assert.equal(store.settings.destination, custom); assert.match(store.error, /设置目录失败/);
  calls.length = 0;
  const restarted = new AppStore(); await restarted.init({ filesDir: root, getApplicationContext: () => ({ setColorMode() {} }) });
  await restarted.saveReceivedCopy(entry, custom, 'session');
  assert.deepEqual(calls, [['activate', custom, 3]], 'existing policy must activate without a new picker or persist call');
  assert.deepEqual(await fs.readFile(entry.exportedPath), Buffer.from([1, 2, 3]));
  const previousExport = entry.exportedPath;
  await restarted.saveReceivedCopy(entry, custom, 'session');
  assert.notEqual(entry.exportedPath, previousExport); assert.match(entry.exportedPath, /file \(1\)\.bin$/);
  assert.deepEqual(await fs.readFile(previousExport), Buffer.from([1, 2, 3]));
  const newestExport = entry.exportedPath;
  kit.fileShare.activatePermission = async () => { throw new Error('grant revoked'); };
  await restarted.saveReceivedCopy(entry, custom, 'revoked');
  assert.equal(entry.exportedPath, newestExport); assert.match(restarted.error, /文件已接收/);
  assert.deepEqual(await fs.readFile(entry.path), Buffer.from([1, 2, 3]));
  assert.equal(handles.size, 0);
  console.log('PASS DOWNLOAD fallback, persistent folder selection, restart activation, cancellation, denied/revoked grants and preserved received bytes');
})().catch(error => { console.error(error); process.exitCode = 1; });
