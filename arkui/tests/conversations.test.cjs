const assert = require('node:assert/strict');
const { load } = require('./host-runtime.cjs');
const { HistoryEntry, Peer, AppStore } = load('model/AppStore');
const { ConversationUpdates, conversationList, conversationTargets, currentConversationPeer, inConversation, messageBatches, messageKey, batchStatus, peerKey } = load('model/Conversations');
const oldPeer = new Peer(); oldPeer.alias = 'Laptop'; oldPeer.ip = '192.168.1.2'; oldPeer.fingerprint = 'identity-a';
const movedPeer = new Peer(); movedPeer.alias = 'Renamed laptop'; movedPeer.ip = '192.168.1.99'; movedPeer.fingerprint = 'identity-a';
const stranger = new Peer(); stranger.alias = 'Laptop'; stranger.ip = '192.168.1.3'; stranger.fingerprint = 'identity-b';
function entry(peer, time, text) { const item = new HistoryEntry(); item.peer = peer.alias; item.peerInfo = peer; item.time = time; item.text = text; return item; }
const a = entry(oldPeer, 1, 'old'); const b = entry(movedPeer, 3, 'new'); const c = entry(stranger, 2, 'other');
const groups = conversationList([a, c, b]);
assert.equal(groups.length, 2); assert.equal(groups[0].count, 2); assert.equal(groups[0].last.text, 'new');
assert.equal(groups[0].peer.alias, 'Renamed laptop');
assert.equal(inConversation(a, movedPeer), true); assert.equal(inConversation(c, oldPeer), false);
const legacy = new HistoryEntry(); legacy.peer = 'Laptop';
assert.equal(inConversation(legacy, oldPeer), true);
assert.equal(conversationList([a, c, b], 'old')[0].last.text, 'new', 'search finds earlier messages but keeps latest preview');
assert.equal(conversationList([a, c, b], 'Laptop').length, 2);
assert.equal(conversationList([a, c, b], 'missing').length, 0);
const store = new AppStore(); store.favorites = [oldPeer];
assert.equal(store.isFavorite(movedPeer), true);
const replacement = new Peer(); replacement.ip = oldPeer.ip; replacement.port = oldPeer.port; replacement.fingerprint = 'replacement';
assert.equal(currentConversationPeer(oldPeer, [replacement, movedPeer]), movedPeer);
assert.equal(peerKey(currentConversationPeer(oldPeer, [movedPeer])), peerKey(oldPeer), 'live refresh preserves draft identity');
assert.equal(currentConversationPeer(oldPeer, [replacement]), oldPeer, 'reused IP cannot replace a known conversation identity');
assert.equal(currentConversationPeer(oldPeer, []), oldPeer, 'temporary discovery absence retains the known endpoint');
const offline = Object.assign(new Peer(), { fingerprint: oldPeer.fingerprint, alias: oldPeer.alias });
assert.equal(currentConversationPeer(offline, [movedPeer]), movedPeer, 'known offline identity can become replyable without reopening');
assert.equal(store.isFavorite(replacement), false, 'IP reuse must not inherit a known fingerprint favorite');
const targets = conversationTargets([movedPeer, replacement], [oldPeer, stranger]);
assert.deepEqual(targets, [movedPeer, replacement, stranger], 'nearby address wins for the same identity; a different identity sharing an old IP remains separate');
assert.deepEqual(conversationTargets([movedPeer], [oldPeer, stranger], '192.168.1.3'), [stranger]);
assert.deepEqual(conversationTargets([movedPeer], [oldPeer], 'renamed'), [movedPeer]);
console.log('PASS conversations follow identity across address/name changes, separate same-name devices, sort newest first, and retain legacy history');
const updates = new ConversationUpdates(); updates.reset([a], oldPeer);
assert.equal(updates.observe([a, b, c], movedPeer), 1, 'only new messages in this identity count');
const exported = { ...b, exportedPath: 'new location' };
assert.equal(updates.observe([a, exported, c], movedPeer), 0, 'metadata refresh is not a new message');
const sent = entry(movedPeer, 4, 'my reply'); sent.direction = 'send';
assert.equal(updates.observe([a, exported, c, sent], movedPeer), 0);
assert.equal(updates.observe([a, exported, c, sent], stranger), 0, 'changing conversation resets the baseline');
console.log('PASS new-message tracking excludes old history, other devices, own replies and metadata updates');
const files = ['one.jpg', 'two.pdf', 'three.zip'].map((name, index) => {
  const item = entry(oldPeer, 10, ''); item.name = name; item.transferId = 'batch-1'; item.size = index + 1; return item;
});
files[1].status = 'cancelled'; files[2].status = 'skipped';
let batches = messageBatches([a, ...files, b]);
assert.equal(batches.length, 3); assert.equal(batches[2].entries.length, 3); assert.equal(batches[2].size, 6);
assert.equal(batchStatus(batches[2]), '部分完成');
const searched = messageBatches([a, ...files, b], 'TWO.PDF');
assert.equal(searched.length, 1); assert.equal(searched[0].entries.length, 3, 'a matching file retains its complete batch');
files[2].status = 'transferring'; assert.equal(batchStatus(messageBatches(files)[0]), '接收中…');
files[2].status = 'waiting'; assert.equal(batchStatus(messageBatches(files)[0]), '等待确认');
files[0].status = 'error'; files[2].status = 'cancelled'; assert.equal(batchStatus(messageBatches(files)[0]), '传输失败');
const otherDevice = { ...files[0], id: 'other-device', peerInfo: stranger };
const otherDirection = { ...files[0], id: 'outgoing', direction: 'send' };
const anotherTransfer = { ...files[0], id: 'another', transferId: 'batch-2' };
assert.equal(messageBatches([...files, otherDevice, otherDirection, anotherTransfer]).length, 4);
const ungrouped = files.map(item => ({ ...item, transferId: '' }));
assert.equal(messageBatches(ungrouped).length, 3, 'legacy rows without a transfer identity must not be guessed into a batch');
const texts = files.map(item => ({ ...item, text: 'text' }));
assert.equal(messageBatches(texts).length, 3, 'text messages retain individual bubbles');
assert.equal(conversationList(files)[0].count, 1, 'conversation count follows displayed messages rather than files');
updates.reset([], oldPeer); assert.equal(updates.observe(files, oldPeer), 1, 'a multi-file transfer counts as one incoming message');
files[1].status = 'complete'; assert.equal(updates.observe(files, oldPeer), 0);
const importedA = { ...files[0], id: 'flutter:message:original-batch:item-a', transferId: '' };
const importedB = { ...files[0], id: 'flutter:message:original-batch:item-b', transferId: '' };
assert.equal(messageKey(importedA), messageKey(importedB), 'older imported message IDs preserve explicit batch identity');
console.log('PASS batch grouping, contextual search, identity/direction isolation, partial states, legacy compatibility and unread counts');
