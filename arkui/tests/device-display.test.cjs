const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { load, mocks } = require('./host-runtime.cjs');
const { AppStore, AppSettings, Peer } = load('model/AppStore');
const { LocalSendService } = load('network/LocalSendService');
const { selectedSendTargets } = load('model/SendTargets');
const { peerKey } = load('model/Conversations');
(async () => {
  assert.equal(new AppSettings().showAddressTags, true);
  const store = new AppStore(); store.settings.fingerprint = 'local';
  const service = new LocalSendService(store);
  const make = (ip, fingerprint = 'remote') => Object.assign(new Peer(), { ip, alias: 'same name', fingerprint, protocol: 'https' });
  const a = make('192.168.1.12'), b = make('10.0.0.12'), c = make('fe80::12%wlan0');
  service.upsertPeer(a); service.upsertPeer(b); service.upsertPeer(c);
  assert.equal(store.displayedPeers.length, 3, '# mode retains distinct endpoints, including equal suffixes');
  assert.equal(store.displayedAddresses(a), '192.168.1.12:53317');
  store.settings.showAddressTags = false;
  assert.equal(store.displayedPeers.length, 1, 'merge by identity rather than name/address');
  assert.equal(store.displayedPeers[0].ip, c.ip);
  const summary = store.displayedAddresses(c);
  for (const address of ['192.168.1.12:53317', '10.0.0.12:53317', '[fe80::12%wlan0]:53317']) assert.ok(summary.includes(address));
  service.upsertPeer(make('192.168.1.13', 'other'));
  assert.equal(store.displayedPeers.length, 2, 'same display names never merge different identities');
  service.upsertPeer(make('192.168.1.12'));
  assert.equal(store.peerEndpoints.length, 4, 'repeated announcements update rather than duplicate');
  store.settings.showAddressTags = true;
  assert.equal(store.displayedPeers.length, 4, 'switching back restores all addresses without rescan');
  assert.equal(selectedSendTargets([peerKey(a)], store.peers, []).length, 1, 'batch selection still sends once per device');
  store.settings.showAddressTags = false;
  service.upsertPeer(make('10.0.1.1', 'ab'.repeat(32)));
  service.upsertPeer(make('10.0.1.2', 'AB'.repeat(32)));
  assert.equal(store.displayedPeers.length, 3, 'hex certificate fingerprint casing cannot split a device');
  assert.ok(store.displayedAddresses(store.peers[0]).includes('10.0.1.1:53317'));
  const work = path.join(__dirname, '../logs/device-display-' + Date.now()); await fs.mkdir(work, { recursive: true });
  const context = { filesDir: work, getApplicationContext: () => ({ setColorMode() {} }) };
  const persisted = new AppStore(); await persisted.init(context);
  persisted.settings.showAddressTags = false; await persisted.save();
  mocks['@kit.ArkData'].preferences.getPreferences = async () => persisted.storage;
  const reopened = new AppStore(); await reopened.init(context);
  assert.equal(reopened.settings.showAddressTags, false);
  await reopened.restoreSettings(); assert.equal(reopened.settings.showAddressTags, true);
  console.log('PASS default # mode, per-address rows, fingerprint merging, IPv6/full addresses, same-name isolation, instant switch, batch deduplication and persisted preference');
})().catch(error => { console.error(error); process.exitCode = 1; });
