const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { load, handles } = require('./host-runtime.cjs');
const { AppStore, HistoryEntry } = load('model/AppStore');
const work = path.join(__dirname, '../logs/batch-actions-' + Date.now());
(async () => {
  await fs.mkdir(work, { recursive: true });
  const store = new AppStore(); await store.init({ filesDir: work, getApplicationContext: () => ({ setColorMode() {} }) });
  const first = new HistoryEntry(); first.name = 'folder/照片.txt'; first.path = path.join(work, 'first.txt');
  await fs.writeFile(first.path, '内容 🌿'); first.size = 1;
  const second = new HistoryEntry(); second.name = 'second.txt'; second.path = path.join(work, 'second.txt');
  await fs.writeFile(second.path, 'second');
  const missing = new HistoryEntry(); missing.name = 'missing.txt'; missing.path = path.join(work, 'missing.txt');
  store.addText('existing selection'); const existing = store.files[0], originalSelection = store.files;
  assert.equal(await store.resendEntries([first, missing]), false);
  assert.equal(store.files, originalSelection, 'a later unreadable file must leave the entire selection unchanged');
  assert.equal(store.files.length, 1); assert.equal(store.files[0], existing);
  assert.equal(store.incomingShare, false); assert.equal(store.busy, false); assert.equal(handles.size, 0);
  assert.equal(await store.resendEntries([first, second, first]), true);
  assert.equal(store.files.length, 3); assert.equal(store.files[0], existing);
  assert.equal(store.files.find(file => file.name === first.name).size, Buffer.byteLength('内容 🌿'), 'read actual file metadata, not stale history size');
  assert.equal(store.incomingShare, true); assert.equal(handles.size, 0);
  await store.resendEntries([first, second]); assert.equal(store.files.length, 3, 'existing source URIs are not added twice');
  const text = new HistoryEntry(); text.text = '再次发送 🌿';
  await store.resendEntries([text]); assert.equal(store.files.at(-1).size, Buffer.byteLength(text.text));
  const before = store.files; store.busy = true;
  assert.equal(await store.resendEntries([second]), false); assert.equal(store.files, before); store.busy = false;
  const unavailable = new HistoryEntry(); unavailable.name = 'not-received.bin';
  assert.equal(await store.resendEntries([first, unavailable]), false); assert.equal(store.files, before);
  await store.addHistory(first); await store.addHistory(second); await store.addHistory(text);
  store.removeHistories([first.id, second.id]); await store.save();
  assert.deepEqual(Array.from(store.history, entry => entry.id), [text.id]);
  assert.deepEqual(JSON.parse(await store.storage.get('history', '[]')).map(entry => entry.id), [text.id]);
  assert.equal(await fs.readFile(first.path, 'utf8'), '内容 🌿'); assert.equal(await fs.readFile(second.path, 'utf8'), 'second');
  assert.equal(handles.size, 0);
  console.log('PASS batch resend is atomic, preserves selection, deduplicates sources, checks files and handles; batch deletion preserves disk files and unrelated history');
})().catch(error => { console.error(error); process.exitCode = 1; });
