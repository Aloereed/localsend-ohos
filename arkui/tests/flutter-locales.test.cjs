const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const { readCatalog, classes, classPaths, getters, resolve, dartString } = require('../flutter-translations.cjs');
const { load, mocks } = require('./host-runtime.cjs');
const { uiText, resolvedLanguage, isRtlLanguage } = load('model/Locale');
const { flutterLanguages } = load('model/FlutterLocales');
const catalog = readCatalog();
assert.equal(Object.keys(catalog.locales).length, 53); assert.equal(flutterLanguages.length, 53);
assert.equal(new Set(flutterLanguages.map(item => item.id)).size, 53);
assert.equal(catalog.locales.de['messageTab.title'], 'Messages', 'a missing localized message class inherits runtime English');
assert.equal(catalog.locales['zh-CN']['messageTab.title'], '消息');
assert.equal(catalog.locales['zh-CN']['sendTab.title'], '发送', 'misplaced Path comments must not move Send into Message');
assert.equal(catalog.locales.en.appName, 'AloeSend', 'read the modified runtime source, not stale JSON branding');
assert.equal(catalog.locales.de['receiveOptionsPage.destination'], catalog.locales.de['settingsTab.receive.destination']);
assert.equal(dartString("'don\\'t; \\u{1F33F} \\n'"), "don't; 🌿 \n");
assert.equal(resolve({ literal: { value: 'cost \u0000value' }, alias: { reference: 'literal' } }).alias, 'cost $value');
assert.throws(() => resolve({ a: { reference: 'b' }, b: { reference: 'a' } }), /Cyclic/);
assert.throws(() => resolve({ a: { reference: 'missing' } }), /Missing/);
assert.throws(() => resolve({ a: { value: '${unsafe}' } }), /Unresolved/);
const source = "class Translations { late final WordsEn words = WordsEn(); }\nclass WordsEn { String get title => 'a; b'; }";
const paths = classPaths(classes(source)); assert.equal(resolve(getters(source, paths, true).values)['words.title'], 'a; b');
execFileSync(process.execPath, [require('node:path').join(__dirname, '../sync-locales.cjs'), '--check']);
assert.equal(uiText('取消', 'de-DE'), catalog.locales.de['general.cancel']);
assert.equal(uiText('发送', 'ja-JP'), catalog.locales.ja['sendTab.title']);
assert.equal(uiText('设备名称', 'zh-Hant-TW'), catalog.locales['zh-TW']['settingsTab.network.alias']);
assert.equal(uiText('接收', 'en-US'), 'Receive');
assert.equal(uiText('设备此刻的名字', 'fr'), '设备此刻的名字', 'unrecognized user content must not be translated');
assert.equal(uiText('打开所选文件失败', 'fr'), 'Could not open the selected file', 'native-only copy uses an explicit English fallback');
assert.equal(resolvedLanguage('zh-Hans-TW'), 'zh'); assert.equal(resolvedLanguage('zh-Hant-HK'), 'zh-HK');
assert.equal(resolvedLanguage('sr_Cyrl_RS'), 'sr-Cyrl'); assert.equal(resolvedLanguage('pt-PT-x-private'), 'pt-PT');
assert.equal(resolvedLanguage('unsupported-ZZ'), 'en');
const language = mocks['@kit.LocalizationKit'].i18n.System.getSystemLanguage;
mocks['@kit.LocalizationKit'].i18n.System.getSystemLanguage = () => 'ar-EG';
assert.equal(resolvedLanguage('system'), 'ar'); assert.equal(isRtlLanguage('system'), true);
mocks['@kit.LocalizationKit'].i18n.System.getSystemLanguage = language;
assert.equal(isRtlLanguage('ur-PK'), true); assert.equal(isRtlLanguage('ja'), false);
console.log('PASS 53 runtime locale variants, inheritance, references, escapes, source synchronization, regional/script tags, fallback and RTL');
