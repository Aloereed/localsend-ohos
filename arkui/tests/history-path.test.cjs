const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { load, mocks, handles } = require('./host-runtime.cjs');
const { AppStore, HistoryEntry } = load('model/AppStore');
(async () => {
  const work = path.join(__dirname, '../logs/history-path-' + Date.now()); await fs.mkdir(work, { recursive: true });
  const store = new AppStore(), opened = [];
  await store.init({ filesDir: work, getApplicationContext: () => ({ setColorMode() {} }), startAbility: async want => opened.push(want) });
  const original = path.join(work, 'original.txt'), copy = path.join(work, 'copy.txt'), destination = path.join(work, 'export.txt');
  await fs.writeFile(original, 'original'); await fs.writeFile(copy, 'copy'); await fs.writeFile(destination, '');
  const entry = Object.assign(new HistoryEntry(), { name: 'document.txt', path: original, exportedPath: copy });
  await store.openFile(entry); assert.equal(opened[0].uri, original, 'readable original is preferred');
  await fs.unlink(original);
  await store.openFile(entry); assert.equal(opened[1].uri, copy, 'missing original falls back to recorded copy');
  assert.equal(entry.path, original, 'fallback must not rewrite the original history location');
  assert.equal(await store.resendEntries([entry]), true);
  assert.equal(store.files[0].uri, copy); assert.equal(store.files[0].size, 4);
  assert.equal(store.files[0].name, 'document.txt');
  const selection = store.files;
  const missing = Object.assign(new HistoryEntry(), { path: path.join(work, 'absent.bin') });
  assert.equal(await store.resendEntries([entry, missing]), false);
  assert.equal(store.files, selection, 'a later missing source preserves the entire selection');
  const shared = [], sharing = mocks['@kit.ShareKit'].systemShare;
  sharing.SharedData = class { constructor(record) { this.record = record; } };
  sharing.ShareController = class { constructor(data) { this.data = data; } async show() { shared.push(this.data.record); } };
  sharing.SharePreviewMode = { DETAIL: 1 };
  await store.shareEntry(entry); assert.equal(shared[0].uri, copy);
  const copyOnly = Object.assign(new HistoryEntry(), { name: 'document.txt', exportedPath: copy });
  await store.shareEntry(copyOnly); assert.equal(shared[1].uri, copy);
  assert.equal(await store.resendEntries([copyOnly]), true);
  assert.equal(store.files.length, 1, 'the resolved copy URI is deduplicated');
  let saves = 0;
  const picker = mocks['@kit.CoreFileKit'].picker;
  picker.DocumentSaveOptions = class {};
  picker.DocumentViewPicker = class { async save() { saves++; return [destination]; } };
  await store.exportFile(entry);
  assert.equal(await fs.readFile(destination, 'utf8'), 'copy'); assert.equal(saves, 1);
  assert.equal(entry.exportedPath, destination);
  await fs.unlink(destination);
  await store.exportFile(entry);
  assert.equal(saves, 1, 'missing sources must fail before opening a save picker');
  assert.match(store.error, /移动或删除/);
  await store.openFile(entry); assert.equal(opened.length, 2, 'no viewer is launched for unavailable files');
  assert.equal(handles.size, 0);
  console.log('PASS original preference, exported-copy fallback, pre-picker validation and closed handles');
})().catch(error => { console.error(error); process.exitCode = 1; });
