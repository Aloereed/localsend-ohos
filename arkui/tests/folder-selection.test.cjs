const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { load, mocks, handles, capabilities } = require('./host-runtime.cjs');
const { AppStore, ShareFile } = load('model/AppStore');
const { insideDownloadFolder, downloadSubfolders, downloadFolderFiles } = load('platform/DownloadFolders');
const work = path.join(__dirname, '../logs/folder-picker-' + Date.now()).replaceAll('\\', '/');
(async () => {
  const root = work + '/Download/com.aloereed.aloesend';
  await fs.mkdir(root + '/相册/子目录', { recursive: true });
  await fs.mkdir(root + '/空文件夹'); await fs.mkdir(root + '/.hidden');
  await fs.writeFile(root + '/相册/照片.png', Buffer.from([0, 128, 255]));
  await fs.writeFile(root + '/相册/子目录/hello.txt', 'hello');
  await fs.writeFile(root + '/ordinary.txt', 'ordinary');
  assert.deepEqual(Array.from(await downloadSubfolders(root, root)), ['相册', '空文件夹']);
  assert.equal(insideDownloadFolder(root, root + '/相册'), true);
  assert.equal(insideDownloadFolder(root, root + '-other'), false);
  assert.equal(insideDownloadFolder(root, root + '/../outside'), false);
  const nativeFs = mocks['@kit.CoreFileKit'].fileIo; const originalLstat = nativeFs.lstat;
  nativeFs.lstat = async file => file === root + '/相册' ? { isDirectory: () => true, isSymbolicLink: () => true } : originalLstat(file);
  await assert.rejects(downloadFolderFiles(root, root + '/相册'), /文件夹/);
  nativeFs.lstat = originalLstat;
  const store = new AppStore(); store.downloadDirectory = root;
  await store.init({ filesDir: work, getApplicationContext: () => ({ setColorMode() {} }) });
  store.downloadAccess = true; capabilities.folderSelection = false;
  let picked = 0;
  store.onPickDownloadDirectory = async (initial, purpose) => { picked++; assert.equal(initial, root); assert.equal(purpose, 'send'); return root + '/相册'; };
  await store.selectFiles('folder'); assert.equal(picked, 1); assert.equal(store.busy, false);
  assert.deepEqual(Array.from(store.files, file => file.name).sort(), ['相册/子目录/hello.txt', '相册/照片.png']);
  assert.equal(store.files.find(file => file.name.endsWith('.png')).size, 3);
  await store.selectFiles('folder'); assert.equal(store.files.length, 2, 'repeated selection does not duplicate source files');
  store.onPickDownloadDirectory = async () => ''; await store.selectFiles('folder'); assert.equal(store.files.length, 2);
  store.onPickDownloadDirectory = async () => root + '/空文件夹'; await store.selectFiles('folder'); assert.equal(store.files.length, 2); assert.match(store.notice, /没有/);
  store.onPickDownloadDirectory = async () => root + '/../outside'; await store.selectFiles('folder'); assert.equal(store.files.length, 2); assert.match(store.error, /下载目录/);
  store.error = ''; store.notice = ''; store.downloadAccess = false;
  store.ensureDownloadAccess = async () => {}; picked = 0;
  store.onPickDownloadDirectory = async () => { picked++; return root; };
  await store.selectFiles('folder'); assert.equal(picked, 0, 'declined DOWNLOAD grant must not open an inaccessible picker');
  assert.equal(store.busy, false); assert.equal(handles.size, 0);
  console.log('PASS custom folder selection without system support, nesting, Unicode, duplicate/cancel/empty behavior, permission and path boundaries');
})().catch(error => { console.error(error); process.exitCode = 1; });
