const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const { load, mocks, handles } = require('./host-runtime.cjs');
const { AppStore } = load('model/AppStore');
const { TlsIdentity } = load('network/TlsIdentity');
const { LocalSendService } = load('network/LocalSendService');
(async () => {
  const root = path.join(__dirname, '../logs/identity-reset-' + Date.now()); await fs.mkdir(root, { recursive: true });
  const store = new AppStore(); await store.init({ filesDir: root, getApplicationContext: () => ({ setColorMode() {} }) });
  const identity = new TlsIdentity(); await identity.load(store); const original = identity.fingerprint;
  await identity.reset(store); assert.notEqual(identity.fingerprint, original);
  const firstReset = identity.fingerprint; await identity.reset(store); assert.notEqual(identity.fingerprint, firstReset);
  const cert = new crypto.X509Certificate(identity.certificate);
  assert.equal(cert.checkPrivateKey(crypto.createPrivateKey(identity.privateKey)), true);
  const current = identity.fingerprint;
  const nativeFs = mocks['@kit.CoreFileKit'].fileIo; const rename = nativeFs.rename;
  nativeFs.rename = async () => { throw new Error('disk full'); };
  await assert.rejects(identity.reset(store), /disk full/); nativeFs.rename = rename;
  const reloaded = new TlsIdentity(); await reloaded.load(store);
  assert.equal(reloaded.fingerprint, current, 'failed replacement preserves the previous identity on disk');
  assert.ok(!(await fs.readdir(root)).some(name => name.endsWith('.tmp')));
  const service = new LocalSendService(store); await service.pause();
  store.identityResetting = true; await service.resume(); await service.restart();
  assert.equal(service.paused, true, 'service controls cannot race an in-progress identity replacement');
  store.identityResetting = false;
  store.transfers = [{ id: 'active', status: 'transferring' }]; await service.resetIdentity();
  assert.equal(store.settings.fingerprint, current, 'active transfer blocks regeneration');
  store.transfers = []; store.webUrl = 'http://sharing'; await service.resetIdentity(); assert.equal(store.settings.fingerprint, current);
  store.webUrl = ''; await service.resetIdentity(); assert.notEqual(store.settings.fingerprint, current);
  assert.equal(store.listenerRunning, false, 'reset preserves a manually paused service'); assert.equal(store.identityResetting, false);
  assert.equal(handles.size, 0); store.notice = '';
  console.log('PASS repeated identity replacement, key/cert pairing, failure rollback, transfer/share guards and paused service preservation');
})().catch(error => { console.error(error); process.exitCode = 1; });
