const assert = require('node:assert/strict');
const { load } = require('./host-runtime.cjs');
const { Peer } = load('model/AppStore');
const { peerKey } = load('model/Conversations');
const { selectedSendTargets } = load('model/SendTargets');
const old = Object.assign(new Peer(), { fingerprint: 'same-device', ip: '192.168.1.2', alias: 'Old name' });
const moved = Object.assign(new Peer(), old, { ip: '192.168.1.20', alias: 'New name', port: 60000 });
const other = Object.assign(new Peer(), old, { fingerprint: 'different-device' });
const key = peerKey(old);
assert.equal(selectedSendTargets([key], [moved], [old])[0], moved);
assert.equal(selectedSendTargets([key, key], [moved, moved], [old]).length, 1);
assert.equal(selectedSendTargets([key], [], [old])[0], old, 'saved offline endpoint stays selectable');
assert.equal(selectedSendTargets([key], [other], []).length, 0, 'IP reuse by another identity does not transfer selection');
assert.equal(selectedSendTargets([key], [], []).length, 0, 'unavailable selections do not inflate the displayed recipient count');
const legacy = Object.assign(new Peer(), { ip: '10.0.0.1', port: 10 });
assert.equal(selectedSendTargets([peerKey(legacy)], [legacy], [])[0], legacy);
assert.equal(selectedSendTargets([peerKey(legacy)], [Object.assign(new Peer(), legacy, { port: 11 })], []).length, 0);
assert.equal(selectedSendTargets([peerKey(legacy)], [Object.assign(new Peer(), legacy, { fingerprint: 'now-known' })], []).length, 0, 'new identity requires explicit selection');
assert.equal(old.ip, '192.168.1.2');
console.log('PASS identity-based recipient selection, moved endpoints, duplicate favorites, offline fallback, disappeared targets and IP reuse');
