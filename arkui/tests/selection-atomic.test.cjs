const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { load, mocks, handles, capabilities } = require('./host-runtime.cjs');
const { AppStore } = load('model/AppStore');
(async () => {
  const work = path.join(__dirname, '../logs/selection-atomic-' + Date.now()).replaceAll('\\', '/');
  await fs.mkdir(work + '/folder/sub', { recursive: true });
  await fs.writeFile(work + '/first.txt', 'first'); await fs.writeFile(work + '/folder/a.txt', 'a');
  await fs.writeFile(work + '/folder/sub/b.txt', 'b');
  await fs.writeFile(work + '/folder/.hidden.txt', 'hidden');
  await fs.writeFile(work + '/folder/.sendignore', '*.txt');
  const store = new AppStore(); await store.init({ filesDir: work, getApplicationContext: () => ({ setColorMode() {} }) });
  store.addText('Existing draft'); const initial = store.files;
  let selected = [], denied = false;
  const picker = mocks['@kit.CoreFileKit'].picker;
  picker.DocumentSelectOptions = class {}; picker.DocumentSelectMode = { FILE: 0, FOLDER: 1 };
  picker.DocumentViewPicker = class { async select() { return selected; } };
  assert.equal(await store.selectFiles('file'), false); assert.equal(store.files, initial);
  selected = [work + '/first.txt', work + '/missing.txt'];
  assert.equal(await store.selectFiles('file'), false); assert.equal(store.files, initial); assert.equal(handles.size, 0);
  selected = [work + '/first.txt', work + '/first.txt'];
  assert.equal(await store.selectFiles('file'), true); assert.equal(store.files.length, 2);
  assert.equal(await store.selectFiles('file'), false); assert.equal(store.files.length, 2);
  capabilities.folderSelection = true; selected = [work + '/folder'];
  const disk = mocks['@kit.CoreFileKit'].fileIo, open = disk.open;
  const beforeFolder = store.files;
  disk.open = async (...args) => { if (args[0].endsWith('/b.txt')) throw new Error('unreadable child'); return open(...args); };
  assert.equal(await store.selectFiles('folder'), false); assert.equal(store.files, beforeFolder); assert.equal(handles.size, 0);
  disk.open = open;
  assert.equal(await store.selectFiles('folder'), true);
  assert.ok(store.files.some(file => file.name === 'folder/sub/b.txt'));
  assert.ok(store.files.some(file => file.name === 'folder/.hidden.txt'), 'hidden files remain part of a selected folder');
  assert.ok(store.files.some(file => file.name === 'folder/.sendignore'), 'Flutter disables SendIgnore; the rule file is transferred normally');
  assert.ok(store.files.some(file => file.name === 'folder/a.txt'), 'disabled ignore rules must not filter matching files');
  store.busy = true; assert.equal(await store.selectFiles('file'), false); store.busy = false;
  mocks['@kit.AbilityKit'].abilityAccessCtrl = { createAtManager: () => { throw new Error('Must not request clipboard permission'); } };
  let clipboard = '  ';
  let hasData = false, reads = 0, readError = false, clearOnRead = false;
  mocks['@kit.BasicServicesKit'].pasteboard.getSystemPasteboard = () => ({
    hasData: async () => hasData,
    getData: async () => { reads++; if (clearOnRead) hasData = false; if (readError) throw new Error('read failed'); return { getPrimaryText: () => clipboard }; }
  });
  const beforePaste = store.files;
  store.error = 'previous error';
  assert.equal(await store.paste(true), false); assert.equal(store.files, beforePaste);
  assert.equal(reads, 0); assert.equal(store.error, ''); assert.equal(store.notice, '剪贴板是空的');
  hasData = true; readError = true; clearOnRead = true;
  assert.equal(await store.paste(true), false); assert.equal(store.error, ''); assert.equal(store.notice, '剪贴板是空的');
  hasData = true; clearOnRead = false;
  assert.equal(await store.paste(true), false); assert.match(store.error, /读取剪贴板失败/);
  readError = false;
  assert.equal(await store.paste(true), false); assert.equal(store.files, beforePaste);
  assert.equal(store.error, ''); assert.equal(store.notice, '剪贴板中没有可发送的文字');
  clipboard = undefined; assert.equal(await store.paste(true), false); assert.equal(store.error, '');
  clipboard = 'clipboard text'; denied = true;
  const beforeDenied = reads;
  assert.equal(await store.paste(false), false); assert.equal(store.files, beforePaste); assert.equal(reads, beforeDenied);
  denied = false; assert.equal(await store.paste(true), true); assert.equal(store.files.at(-1).text, clipboard);
  console.log('PASS cancelled/failed/duplicate selection outcomes, atomic recursive folders, existing draft preservation, clipboard permission and blank text');
})().catch(error => { console.error(error); process.exitCode = 1; });
