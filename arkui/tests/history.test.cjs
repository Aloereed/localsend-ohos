const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { load, handles } = require('./host-runtime.cjs');
const { AppStore, HistoryEntry } = load('model/AppStore');
const work = path.join(__dirname, '../logs/history-fixture-' + Date.now());
(async () => {
  await fs.mkdir(work, { recursive: true });
  const store = new AppStore();
  await store.init({ filesDir: work, getApplicationContext: () => ({ setColorMode() {} }) });
  const saved = new HistoryEntry(); saved.text = 'Previously saved';
  await store.addHistory(saved);
  store.settings.saveHistory = false;
  const temporary = new HistoryEntry(); temporary.text = 'Visible until restart';
  await store.addHistory(temporary);
  assert.equal(store.history.length, 2);
  let persisted = JSON.parse(await store.storage.get('history', '[]'));
  assert.deepEqual(persisted.map(item => item.id), [saved.id]);
  store.settings.saveHistory = true; await store.save();
  persisted = JSON.parse(await store.storage.get('history', '[]'));
  assert.deepEqual(persisted.map(item => item.id), [saved.id], 'changing preference must not persist private session history');
  store.removeHistory(saved.id); await store.save();
  assert.equal(JSON.parse(await store.storage.get('history', '[]')).length, 0);
  console.log('PASS transient history stays visible without being persisted or deleting older saved history');
  const entry = new HistoryEntry(); entry.name = 'trip/photos/a.txt'; entry.path = path.join(work, 'source.txt');
  await fs.writeFile(entry.path, 'content'); await store.addHistory(entry);
  store.settings.destinationMode = 'folder'; store.settings.destination = path.join(work, 'default');
  const temporaryFolder = path.join(work, 'one-transfer');
  await store.saveReceivedCopy(entry, temporaryFolder, 'session-1');
  assert.equal(store.error, '');
  assert.equal(await fs.readFile(path.join(temporaryFolder, 'AloeSend-session-1/trip/photos/a.txt'), 'utf8'), 'content');
  assert.equal(store.settings.destination, path.join(work, 'default'));
  assert.equal(entry.exportedPath, `${temporaryFolder}/AloeSend-session-1/trip/photos/a.txt`);
  entry.exportedPath = ''; await store.saveReceivedCopy(entry, '', 'session-2');
  assert.equal(entry.exportedPath, '', 'explicit private destination must not fall back to default folder');
  assert.equal(handles.size, 0);
  console.log('PASS per-transfer destination preserves folders, global preference and file handles');
  store.addText('old draft'); const original = store.files[0];
  store.editText(original.id, '新草稿 🌿');
  assert.equal(store.files.length, 1); assert.equal(store.files[0].id, original.id);
  assert.equal(store.files[0].size, Buffer.byteLength('新草稿 🌿'));
  assert.equal(original.text, 'old draft', 'editing must not mutate a prior transfer snapshot');
  store.editText(original.id, '  '); assert.equal(store.files[0].text, '新草稿 🌿');
  console.log('PASS editing a selected message preserves identity and updates UTF-8 size without mutating prior snapshots');
})().catch(error => { console.error(error); process.exitCode = 1; });
