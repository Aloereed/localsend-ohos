// Keep native policy content verbatim with Flutter's authoritative policy.
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../app/lib/pages/privacy_policy.dart'), 'utf8');
function readPolicy(locale) {
  let at = source.indexOf(`_${locale} = _PrivacyPolicyContent(`) + `_${locale} = `.length;
  function whitespace() { while (/\s/.test(source[at] || '') && at < source.length) at++; }
  function value() {
    whitespace();
    if (source[at] === "'") {
      at++; let text = '';
      while (at < source.length) {
        const c = source[at++]; if (c === "'") return text;
        if (c === '\\') { const escaped = source[at++]; text += escaped === 'n' ? '\n' : escaped; } else text += c;
      }
      throw new Error('Unterminated policy text');
    }
    if (source[at] === '[') {
      at++; const items = []; whitespace();
      while (source[at] !== ']') { items.push(value()); whitespace(); if (source[at] === ',') at++; whitespace(); }
      at++; return items;
    }
    const type = /^_PrivacyPolicy\w+/.exec(source.slice(at));
    if (!type) throw new Error('Unknown policy value: ' + source.slice(at, at + 30));
    at += type[0].length; whitespace(); if (source[at++] !== '(') throw new Error('Expected constructor');
    const result = {}; whitespace();
    while (source[at] !== ')') {
      const field = /^\w+/.exec(source.slice(at)); if (!field) throw new Error('Expected field');
      at += field[0].length; whitespace(); if (source[at++] !== ':') throw new Error('Expected colon');
      result[field[0]] = value(); whitespace(); if (source[at] === ',') at++; whitespace();
    }
    at++;
    if (type[0] === '_PrivacyPolicySection') { result.paragraphs ||= []; result.bullets ||= []; }
    return result;
  }
  return value();
}
const header = `// Generated by arkui/sync-privacy.cjs from app/lib/pages/privacy_policy.dart.\n` +
  `export interface PolicyBullet { label: string; body: string; }\n` +
  `export interface PolicySection { title: string; paragraphs: string[]; bullets: PolicyBullet[]; }\n` +
  `export interface PrivacyPolicy { heroTitle: string; heroSubtitle: string; lastUpdated: string; effectiveDate: string; highlights: string[]; sections: PolicySection[]; contactTitle: string; contactSubtitle: string; contactEmail: string; company: string; }\n`;
const output = header + ['zh', 'en'].map(locale => `export const policy_${locale}: PrivacyPolicy = ${JSON.stringify(readPolicy(locale), null, 2)};\n`).join('\n');
const target = path.join(__dirname, 'AloeSend/entry/src/main/ets/model/PrivacyPolicy.ets');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Native policy differs from Flutter; run node arkui/sync-privacy.cjs');
  process.stdout.write('Privacy content matches Flutter exactly.\n');
} else fs.writeFileSync(target, output);
