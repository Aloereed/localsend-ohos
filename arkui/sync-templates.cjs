const fs = require('node:fs');
const path = require('node:path');
const { readTemplates } = require('./flutter-templates.cjs');
const catalog = readTemplates();
const keys = ['receivePage.filesCard.selected', 'webSharePage.openLink',
  'webSharePage.pendingRequests', 'webSharePage.filesCount', 'receivePage.filesCard.offered', 'dialogs.fileNameInput.original',
  'settingsTab.network.portWarning', 'settingsTab.network.multicastGroupWarning'];
const values = {};
for (const [locale, templates] of Object.entries(catalog.locales)) {
  values[locale === 'zh-CN' ? 'zh' : locale] = {};
  for (const key of keys) {
    if (!templates[key] || catalog.unsupported[locale][key]) throw new Error(`Unsupported ${locale}:${key}`);
    values[locale === 'zh-CN' ? 'zh' : locale][key] = templates[key];
  }
}
const output = '// Generated by arkui/sync-templates.cjs from Flutter runtime methods and pinned upstream locales. Do not edit.\n' +
  'export interface FlutterTemplate { parameters: string[]; plural: string; locale: string; forms: Record<string, string>; }\n' +
  'export const flutterTemplates: Record<string, Record<string, FlutterTemplate>> = ' + JSON.stringify(values, null, 2) + ';\n';
const target = path.join(__dirname, 'AloeSend/entry/src/main/ets/model/FlutterTemplates.ets');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Flutter templates are stale; run node arkui/sync-templates.cjs');
} else fs.writeFileSync(target, output);
console.log(`Synchronized ${Object.keys(values).length} locales and ${keys.length} dynamic templates.`);
