const fs = require('node:fs');
const path = require('node:path');
const { readCatalog } = require('./flutter-translations.cjs');
const { locales, unsupported } = readCatalog();
if (Object.values(unsupported).some(keys => keys.length)) throw new Error('Unparsed Flutter getters; review before synchronizing');
const keys = JSON.parse(fs.readFileSync(path.join(__dirname, 'flutter-locale-keys.json')));
const options = [], labels = {};
for (const [locale, values] of Object.entries(locales)) {
  const id = locale === 'zh-CN' ? 'zh' : locale;
  if (!values.locale) throw new Error('Locale has no display name: ' + locale);
  options.push({ id, name: id === 'zh-TW' ? '繁體中文' : values.locale }); labels[id] = {};
  for (const [native, key] of Object.entries(keys)) {
    if (!values[key]) throw new Error(`Missing ${locale}:${key}`);
    labels[id][native] = values[key];
  }
}
const output = '// Generated by arkui/sync-locales.cjs from Flutter runtime getters and pinned upstream locales.\n' +
  '// Localized getters inherit the English base, as in Flutter. Do not edit.\n' +
  'export interface LanguageOption { id: string; name: string; }\n' +
  'export const flutterLanguages: LanguageOption[] = ' + JSON.stringify(options, null, 2) + ';\n' +
  'export const flutterLabels: Record<string, Record<string, string>> = ' + JSON.stringify(labels, null, 2) + ';\n';
const target = path.join(__dirname, 'AloeSend/entry/src/main/ets/model/FlutterLocales.ets');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Flutter locale resource is stale; run node arkui/sync-locales.cjs');
} else fs.writeFileSync(target, output);
console.log(`Synchronized ${options.length} Flutter locale variants and ${Object.keys(keys).length} native labels.`);
